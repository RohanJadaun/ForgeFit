import { useEffect, useRef, useState } from "react";
import { useDispatch, useSelector } from "react-redux";
import { Send, Bot, Trash2 } from "lucide-react";
import { clearChat, fetchChat, sendMessage } from "../../store/slices/aiCoachSlice";
import CoachReply from "./CoachReply";

const quickQuestions = ["Build muscle", "Fat loss", "Recovery", "Plan my week"];

function CoachChat() {
  const dispatch = useDispatch();
  const { chat, sending, error, notice, provider, chatLoading, clearingChat } = useSelector((state) => state.aiCoach);
  const [message, setMessage] = useState("");
  const chatEnd = useRef(null);

  useEffect(() => {
    chatEnd.current?.scrollIntoView?.({ behavior: "smooth" });
  }, [chat, sending]);

  useEffect(() => { dispatch(fetchChat()); }, [dispatch]);

  const submit = (event) => {
    event.preventDefault();
    const text = message.trim();
    if (!text || sending) return;
    dispatch(sendMessage({ message: text }));
    setMessage("");
  };

  const ask = (question) => {
    if (!sending) dispatch(sendMessage({ message: question }));
  };

  return (
    <section className="flex min-h-[380px] flex-col rounded-[28px] border border-slate-200 bg-white p-5 shadow-sm" aria-label="AI coach chat">
      <div className="mb-4 flex items-center justify-between">
        <h3 className="font-semibold text-slate-900">Ask AI Coach</h3>
        <div className="flex items-center gap-3">
          <div className="flex items-center gap-1 text-xs text-slate-500" title={provider === "openai" ? "Replies generated by the configured AI provider" : "Personalized built-in guidance based on your logs"}><Bot size={14} /> {provider === "openai" ? "AI coach" : provider === "offline" ? "Offline coach" : "Built-in coach"}</div>
          {chat.length > 0 && <button type="button" disabled={sending || clearingChat} onClick={() => dispatch(clearChat())} className="inline-flex items-center gap-1 rounded-lg px-2 py-1 text-xs font-medium text-slate-500 transition hover:bg-slate-100 hover:text-slate-800 disabled:opacity-50"><Trash2 size={13} /> {clearingChat ? "Clearing..." : "Clear chat"}</button>}
        </div>
      </div>
      {!chat.length && (
        <div className="mb-4 flex flex-wrap gap-2">
          {quickQuestions.map((question) => <button key={question} type="button" onClick={() => ask(question)} disabled={sending || chatLoading || clearingChat} className="rounded-xl border border-slate-200 bg-slate-50 px-3 py-1.5 text-xs font-medium text-slate-700 transition hover:bg-slate-100 disabled:opacity-50">{question}</button>)}
        </div>
      )}
      <div className="flex-1 space-y-3 overflow-y-auto rounded-2xl bg-slate-50/50 p-3" aria-live="polite">
        {chatLoading && <p className="p-2 text-sm text-slate-500" role="status">Loading your coach history...</p>}
        {!chat.length && !chatLoading && <p className="p-2 text-sm text-slate-500">Ask about training, recovery, nutrition, or your weekly plan. Your profile and recent logs help personalize replies.</p>}
        {chat.map((item, index) => <div key={`${index}-${item.type}`} className={`flex ${item.type === "user" ? "justify-end" : "justify-start"}`}><div className={`max-w-[90%] rounded-2xl px-3 py-2 text-sm ${item.type === "user" ? "whitespace-pre-wrap bg-blue-600 leading-relaxed text-white" : "border border-slate-200 bg-white text-slate-700"}`}>{item.type === "user" ? item.text || "" : <CoachReply text={item.text} />}</div></div>)}
        {sending && <p className="text-sm text-slate-500" role="status">Your coach is thinking…</p>}
        <div ref={chatEnd} />
      </div>
      {notice && <p className="mt-2 rounded-lg bg-amber-50 px-3 py-2 text-xs text-amber-800" role="status">{notice}</p>}
      {error && <p className="mt-2 text-sm text-red-600" role="alert">{error}</p>}
      <form onSubmit={submit} className="mt-4 flex gap-2">
        <label className="sr-only" htmlFor="coach-message">Message your coach</label>
        <input id="coach-message" type="text" maxLength={1000} value={message} onChange={(event) => setMessage(event.target.value)} placeholder={chatLoading ? "Loading your history..." : "Ask your coach…"} disabled={chatLoading || clearingChat} className="min-w-0 flex-1 rounded-xl border border-slate-200 bg-white px-4 py-2 text-sm outline-none focus:border-blue-300 disabled:opacity-60" />
        <button type="submit" disabled={!message.trim() || sending || chatLoading || clearingChat} aria-label="Send message" className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-blue-600 text-white transition hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-50"><Send size={16} /></button>
      </form>
      <p className="mt-2 text-xs text-slate-400">General fitness guidance only. The coach uses your recent ForgeFit logs. Stop if you feel pain and seek qualified medical advice when needed.</p>
    </section>
  );
}

export default CoachChat;
